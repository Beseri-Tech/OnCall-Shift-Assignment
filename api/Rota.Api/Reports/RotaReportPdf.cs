using System.Globalization;
using System.Reflection;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Rota.Api.Reports;

/// <summary>Lays a <see cref="RotaReportData"/> out as a PDF: cover page, summary, assignments with reasons, swaps, audit trail.</summary>
public static class RotaReportPdf
{
    private const string Brand = "#0891b2";
    private const string BrandDark = "#155e75";
    private const string Ink = "#1f2933";
    private const string Muted = "#667085";
    private const string Line = "#d0d5dd";
    private const string Tint = "#f2f8fa";
    private const string Credit = "Developed by Beseri-Tech";

    private static readonly byte[] Logo = LoadLogo();

    static RotaReportPdf()
    {
        QuestPDF.Settings.License = LicenseType.Community;
        QuestPDF.Settings.EnableCaching = true;
    }

    private static byte[] LoadLogo()
    {
        using var s = Assembly.GetExecutingAssembly().GetManifestResourceStream("Rota.Api.Reports.logo.png")
                      ?? throw new InvalidOperationException("Report logo is missing from the build.");
        using var ms = new MemoryStream();
        s.CopyTo(ms);
        return ms.ToArray();
    }

    public static byte[] Render(RotaReportData d) => Document.Create(doc =>
    {
        doc.Page(p => { Setup(p, margin: 0); p.Content().Element(c => Cover(c, d)); });
        doc.Page(p => { Setup(p, 36); Frame(p, d); p.Content().Element(c => Body(c, d)); });
    })
    .WithMetadata(new DocumentMetadata
    {
        Title = $"On-call rota report: {d.PeriodName}",
        Author = Credit,
        Subject = "Published rota report",
        Creator = "Rota-OC",
    })
    .GeneratePdf();

    private static void Setup(PageDescriptor p, float margin)
    {
        p.Size(PageSizes.A4);
        p.Margin(margin);
        p.DefaultTextStyle(t => t.FontSize(9).FontColor(Ink));
    }

    // ---------------- cover ----------------

    private static void Cover(IContainer c, RotaReportData d) => c.Column(col =>
    {
        col.Item().Height(14).Background(Brand);
        col.Item().PaddingHorizontal(56).PaddingTop(120).Column(m =>
        {
            m.Item().Width(110).Image(Logo);
            m.Item().PaddingTop(28).Text("ROTA-OC").FontSize(13).Bold().FontColor(Brand).LetterSpacing(0.2f);
            m.Item().PaddingTop(6).Text("Published rota report").FontSize(34).Bold().FontColor(BrandDark);
            m.Item().PaddingTop(10).Text(d.PeriodName).FontSize(22).FontColor(Ink);
            m.Item().PaddingTop(4).Text($"{Long(d.Start)} to {Long(d.End)}").FontSize(12).FontColor(Muted);

            m.Item().PaddingTop(36).Width(60).LineHorizontal(3).LineColor(Brand);

            m.Item().PaddingTop(24).Text(
                "The final on-call assignments, why each officer was placed on each day, every swap and override, and the audit trail, " +
                "kept as a record of how this rota was made.").FontSize(11).FontColor(Muted).LineHeight(1.4f);

            m.Item().PaddingTop(40).Table(t =>
            {
                t.ColumnsDefinition(cd => { cd.ConstantColumn(100); cd.RelativeColumn(); });
                void Row(string k, string v)
                {
                    t.Cell().PaddingVertical(3).Text(k).FontColor(Muted);
                    t.Cell().PaddingVertical(3).Text(v).SemiBold();
                }
                Row("Rota status", d.Status);
                Row("Report generated", d.GeneratedOn);
                Row("Generated by", d.GeneratedBy);
                Row("Rota reference", d.RunId);
            });
        });
        col.Item().ExtendVertical().AlignBottom().Padding(56).Column(f =>
        {
            f.Item().LineHorizontal(0.5f).LineColor(Line);
            f.Item().PaddingTop(10).Text(Credit).FontSize(10).SemiBold().FontColor(BrandDark);
            f.Item().PaddingTop(2).Text("Confidential: for the admin's records. Contains officers' names and leave information.")
                .FontSize(8).FontColor(Muted);
        });
    });

    // ---------------- running header and footer ----------------

    private static void Frame(PageDescriptor p, RotaReportData d)
    {
        p.Header().PaddingBottom(10).Row(r =>
        {
            r.ConstantItem(22).Image(Logo);
            r.RelativeItem().PaddingLeft(8).AlignMiddle().Text(t =>
            {
                t.Span("Rota-OC").Bold().FontColor(BrandDark);
                t.Span($"  ·  {d.PeriodName} rota report").FontColor(Muted);
            });
            r.AutoItem().AlignMiddle().Text($"{Short(d.Start)} to {Short(d.End)}").FontColor(Muted).FontSize(8);
        });
        p.Footer().BorderTop(0.5f).BorderColor(Line).PaddingTop(5).Row(r =>
        {
            r.RelativeItem().Text(Credit).FontSize(8).FontColor(Muted);
            r.RelativeItem().AlignRight().Text(t =>
            {
                t.DefaultTextStyle(x => x.FontSize(8).FontColor(Muted));
                t.Span("Page ");
                t.CurrentPageNumber();
                t.Span(" of ");
                t.TotalPages();
            });
        });
    }

    // ---------------- body ----------------

    private static void Body(IContainer c, RotaReportData d) => c.Column(col =>
    {
        col.Spacing(14);

        col.Item().Element(x => Section(x, "1", "Summary", s =>
        {
            s.Spacing(8);
            s.Item().Element(y => Facts(y, d.Summary));
            if (d.Timeline.Count > 0)
            {
                s.Item().PaddingTop(4).Text("How this rota came about").Bold().FontColor(BrandDark);
                s.Item().Table(t =>
                {
                    t.ColumnsDefinition(cd => { cd.ConstantColumn(105); cd.RelativeColumn(); cd.ConstantColumn(130); });
                    foreach (var st in d.Timeline)
                    {
                        t.Cell().Element(Cell).Text(st.When).FontColor(Muted);
                        t.Cell().Element(Cell).Text(st.What);
                        t.Cell().Element(Cell).Text(st.By).FontColor(Muted);
                    }
                });
            }
            if (d.SpecialDays.Count > 0)
            {
                s.Item().PaddingTop(4).Text("Public holidays and peak days in this rota").Bold().FontColor(BrandDark);
                s.Item().Table(t =>
                {
                    t.ColumnsDefinition(cd => { cd.ConstantColumn(105); cd.ConstantColumn(80); cd.RelativeColumn(); });
                    foreach (var sd in d.SpecialDays)
                    {
                        t.Cell().Element(Cell).Text(Date(sd.Date));
                        t.Cell().Element(Cell).Text(sd.Kind).FontColor(Muted);
                        t.Cell().Element(Cell).Text(sd.Name);
                    }
                });
            }
            if (d.GeneratorNotes.Count > 0)
            {
                s.Item().PaddingTop(4).Text("Generator notes").Bold().FontColor(BrandDark);
                foreach (var n in d.GeneratorNotes) s.Item().Text($"•  {n}");
            }
            if (d.LeftOut.Count > 0)
                s.Item().Text($"Left out of this rota by the admin: {string.Join(", ", d.LeftOut)}.").FontColor(Muted);
        }));

        col.Item().Element(x => Section(x, "2", "Final assignments", s =>
        {
            s.Spacing(6);
            s.Item().Text("One row per day, as published. Weekend and public holiday shifts are shaded.").FontColor(Muted);
            s.Item().Table(t =>
            {
                t.ColumnsDefinition(cd => { cd.ConstantColumn(78); cd.ConstantColumn(36); cd.RelativeColumn(); cd.ConstantColumn(110); });
                t.Header(h =>
                {
                    HeadCell(h.Cell(), "Date"); HeadCell(h.Cell(), "Day"); HeadCell(h.Cell(), "Officer on call"); HeadCell(h.Cell(), "Day type");
                });
                foreach (var day in d.Days)
                {
                    string bg = day.IsWeekendHoliday ? Tint : "#ffffff";
                    IContainer C(IContainer x) => Cell(x).Background(bg);
                    t.Cell().Element(C).Text(Date(day.Date));
                    t.Cell().Element(C).Text(day.Date.ToString("ddd", CultureInfo.InvariantCulture)).FontColor(Muted);
                    t.Cell().Element(C).Text(day.Officer ?? "Unassigned").SemiBold().FontColor(day.Officer is null ? "#b42318" : Ink);
                    t.Cell().Element(C).Text(Brief(day.DayKind)).FontColor(Muted);
                }
            });
        }));

        col.Item().PageBreak();

        col.Item().Element(x => Section(x, "3", "Why each officer is on each day", s =>
        {
            s.Spacing(6);
            s.Item().Text(
                "The generator spreads shifts so everyone gets the same number of shifts, weekend and public holiday duty is shared fairly " +
                "(taking earlier rotas into account), nobody is placed on leave, blocked or clinic-blocked days, and preferred dates are " +
                "honoured where possible. The notes below show what applied to each day. \"Path\" lists everyone who held the day, in order.")
                .FontColor(Muted).LineHeight(1.3f);
            foreach (var day in d.Days)
            {
                s.Item().ShowEntire().PaddingTop(4).BorderLeft(2.5f).BorderColor(day.Source == "Generator" ? Brand : "#f79009")
                    .PaddingLeft(8).Column(x =>
                    {
                        x.Item().Row(r =>
                        {
                            r.RelativeItem().Text(t =>
                            {
                                t.Span($"{Date(day.Date)}  ").Bold();
                                t.Span(day.Officer ?? "Unassigned").Bold().FontColor(BrandDark);
                            });
                            r.AutoItem().Text($"{Brief(day.DayKind)}  ·  {day.Source}").FontColor(Muted).FontSize(8);
                        });
                        foreach (var reason in day.Reasons)
                            x.Item().PaddingTop(1).Text($"•  {reason}").LineHeight(1.25f);
                        if (day.Path.Count > 1)
                            x.Item().PaddingTop(2).Text($"Path: {string.Join("  →  ", day.Path)}").FontColor("#b54708").FontSize(8.5f);
                    });
            }
        }));

        col.Item().PageBreak();

        col.Item().Element(x => Section(x, "4", "Officers: totals and leave points", s =>
        {
            s.Spacing(6);
            s.Item().Text(
                "Shifts in this rota, the officer's shifts before it (the admin's tally plus earlier published rotas), and how they used " +
                "their leave points. The reward column is what the officer earns for the next rota from the busy days they worked here " +
                "(public holiday +3, weekend +2, peak day +1).").FontColor(Muted).LineHeight(1.3f);
            s.Item().Table(t =>
            {
                t.ColumnsDefinition(cd =>
                {
                    cd.RelativeColumn(2.6f); cd.ConstantColumn(28); cd.ConstantColumn(28); cd.ConstantColumn(30); cd.ConstantColumn(34);
                    cd.ConstantColumn(34); cd.ConstantColumn(42); cd.ConstantColumn(44); cd.RelativeColumn(1.4f);
                });
                t.Header(h =>
                {
                    HeadCell(h.Cell(), "Officer"); HeadCell(h.Cell(), "Shifts"); HeadCell(h.Cell(), "Wkdy"); HeadCell(h.Cell(), "W/E+PH");
                    HeadCell(h.Cell(), "Before"); HeadCell(h.Cell(), "Leave"); HeadCell(h.Cell(), "Points"); HeadCell(h.Cell(), "Prefs");
                    HeadCell(h.Cell(), "Next-rota reward");
                });
                foreach (var o in d.Officers)
                {
                    t.Cell().Element(Cell).Column(x =>
                    {
                        x.Item().Text($"{o.Name}").SemiBold();
                        x.Item().Text($"{o.Code}{(o.Clinic is null ? "" : "  ·  " + o.Clinic)}").FontSize(7.5f).FontColor(Muted);
                        if (o.Flags is not null) x.Item().Text(o.Flags).FontSize(7.5f).FontColor("#b54708");
                    });
                    t.Cell().Element(Cell).Text(o.Total.ToString());
                    t.Cell().Element(Cell).Text(o.Weekday.ToString());
                    t.Cell().Element(Cell).Text(o.WeekendHoliday.ToString());
                    t.Cell().Element(Cell).Text(o.PriorWeekendHoliday?.ToString() ?? "n/a");
                    t.Cell().Element(Cell).Text(o.ConfirmedDays > 0 ? $"{o.LeaveDays} ({o.ConfirmedDays} CL)" : o.LeaveDays.ToString());
                    t.Cell().Element(Cell).Column(x =>
                    {
                        x.Item().Text($"{o.PointsUsed}/{o.PointsBudget}");
                        x.Item().Text(o.BudgetDetail).FontSize(7).FontColor(Muted);
                    });
                    t.Cell().Element(Cell).Text(o.PreferredTotal == 0 ? "none" : $"{o.PreferredHonoured} of {o.PreferredTotal}");
                    t.Cell().Element(Cell).Text(o.EarnedReward);
                }
            });
            s.Item().Text("Wkdy = ordinary weekday shifts. W/E+PH = weekend and public holiday shifts. Before = weekend and public holiday " +
                          "shifts done before this rota. Leave = leave days in the period (CL = confirmed leave, included). " +
                          "Points = leave points used / available. Prefs = preferred dates given / honoured.")
                .FontSize(8).FontColor(Muted);
        }));

        col.Item().Element(x => Section(x, "5", "Swap history", s =>
        {
            s.Spacing(6);
            s.Item().Text("Every swap request made while the rota was in review, including the ones that were declined, withdrawn or closed.")
                .FontColor(Muted);
            if (d.Swaps.Count == 0)
            {
                s.Item().Text("No swaps were requested for this rota.").Italic();
                return;
            }
            s.Item().Table(t =>
            {
                t.ColumnsDefinition(cd =>
                {
                    cd.ConstantColumn(78); cd.RelativeColumn(1.6f); cd.RelativeColumn(1.6f); cd.ConstantColumn(58); cd.ConstantColumn(78);
                });
                t.Header(h =>
                {
                    HeadCell(h.Cell(), "Requested"); HeadCell(h.Cell(), "Requester gives"); HeadCell(h.Cell(), "Other officer gives");
                    HeadCell(h.Cell(), "Result"); HeadCell(h.Cell(), "Answered");
                });
                foreach (var sw in d.Swaps)
                {
                    t.Cell().Element(Cell).Text(sw.Requested).FontSize(8);
                    t.Cell().Element(Cell).Column(x =>
                    {
                        x.Item().Text(sw.Requester).SemiBold();
                        x.Item().Text(sw.GivesDate).FontColor(Muted);
                        if (sw.Note is not null) x.Item().Text($"\"{sw.Note}\"").Italic().FontSize(8).FontColor(Muted);
                    });
                    t.Cell().Element(Cell).Column(x =>
                    {
                        x.Item().Text(sw.With).SemiBold();
                        x.Item().Text(sw.TakesDate).FontColor(Muted);
                    });
                    t.Cell().Element(Cell).Text(sw.Status).Bold().FontColor(sw.Status == "Accepted" ? "#027a48" : Muted);
                    t.Cell().Element(Cell).Text(sw.Answered).FontSize(8);
                }
            });
        }));

        col.Item().Element(x => Section(x, "6", "Audit trail", s =>
        {
            s.Spacing(6);
            s.Item().Text("Admin and officer actions recorded against this rota: generation, manual overrides, review, accepted swaps and publishing.")
                .FontColor(Muted);
            if (d.Changes.Count == 0)
            {
                s.Item().Text("No actions were recorded for this rota.").Italic();
                return;
            }
            s.Item().Table(t =>
            {
                t.ColumnsDefinition(cd => { cd.ConstantColumn(95); cd.ConstantColumn(115); cd.RelativeColumn(); });
                t.Header(h => { HeadCell(h.Cell(), "When"); HeadCell(h.Cell(), "Who"); HeadCell(h.Cell(), "What"); });
                foreach (var ch in d.Changes)
                {
                    t.Cell().Element(Cell).Text(ch.When).FontSize(8);
                    t.Cell().Element(Cell).Text(ch.By).FontSize(8.5f);
                    t.Cell().Element(Cell).Column(x =>
                    {
                        x.Item().Text(ch.What).SemiBold();
                        if (ch.Detail is not null) x.Item().Text(ch.Detail).FontColor(Muted).FontSize(8);
                    });
                }
            });
        }));

        col.Item().Element(x => Section(x, "7", "Rules applied", s =>
        {
            s.Spacing(6);
            s.Item().Text("The leave and reward settings in force when this report was produced.").FontColor(Muted);
            s.Item().Element(y => Facts(y, d.Rules));
            s.Item().PaddingTop(6).Text(
                "This report is generated from the live system records. Names, leave and preferences are as they stand on the generation date " +
                "above; the audit trail is a permanent record of changes.").FontSize(8).FontColor(Muted);
        }));
    });

    // ---------------- building blocks ----------------

    private static void Section(IContainer c, string number, string title, Action<ColumnDescriptor> content) => c.Column(col =>
    {
        col.Item().PaddingBottom(6).Row(r =>
        {
            r.AutoItem().Background(Brand).PaddingHorizontal(6).PaddingVertical(2).Text(number).Bold().FontColor(Colors.White);
            r.RelativeItem().PaddingLeft(8).AlignMiddle().Text(title).FontSize(14).Bold().FontColor(BrandDark);
        });
        col.Item().Column(content);
    });

    private static void Facts(IContainer c, IReadOnlyList<ReportFact> facts) => c.Table(t =>
    {
        t.ColumnsDefinition(cd => { cd.RelativeColumn(1); cd.RelativeColumn(1.4f); cd.RelativeColumn(1); cd.RelativeColumn(1.4f); });
        foreach (var f in facts)
        {
            t.Cell().Element(Cell).Text(f.Label).FontColor(Muted);
            t.Cell().Element(Cell).Text(f.Value).SemiBold();
        }
        if (facts.Count % 2 == 1) { t.Cell().Element(Cell).Text(""); t.Cell().Element(Cell).Text(""); }
    });

    private static IContainer Cell(IContainer c) =>
        c.BorderBottom(0.5f).BorderColor(Line).PaddingVertical(3).PaddingHorizontal(3);

    private static void HeadCell(IContainer c, string text) =>
        c.Background(BrandDark).PaddingVertical(4).PaddingHorizontal(3).Text(text).Bold().FontSize(8).FontColor(Colors.White);

    private static string Date(DateOnly d) => d.ToString("d MMM yyyy", CultureInfo.InvariantCulture);
    private static string Short(DateOnly d) => d.ToString("d MMM", CultureInfo.InvariantCulture);
    private static string Long(DateOnly d) => d.ToString("d MMMM yyyy", CultureInfo.InvariantCulture);

    /// <summary>"Public holiday: Hari Raya" becomes "Public holiday" in the compact table.</summary>
    private static string Brief(string kind) => kind.Contains(':') ? kind[..kind.IndexOf(':')] : kind;
}
